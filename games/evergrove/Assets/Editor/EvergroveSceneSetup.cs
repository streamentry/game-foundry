using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace Evergrove.UnityClient.Editor
{
    public static class EvergroveSceneSetup
    {
        [MenuItem("Evergrove/Create Playtest Scene")]
        public static void CreateScene()
        {
            const string path = "Assets/Scenes/Evergrove.unity";
            if (!Directory.Exists("Assets/Scenes")) Directory.CreateDirectory("Assets/Scenes");
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            if (!EditorSceneManager.SaveScene(scene, path))
            {
                Debug.LogError("Could not save Evergrove scene");
                return;
            }
            EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(path, true) };
            AssetDatabase.Refresh();
            EditorUtility.DisplayDialog("Evergrove", "Scene created. Press Play. All UI is generated by C# at runtime.", "OK");
        }
    }
}
